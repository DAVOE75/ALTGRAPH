    fun getKmCoefficient(gradientPct: Double): Float {
        if (gradientPct <= 0.0) return 1.0f
        val index = (gradientPct * 10.0).roundToInt()
        return when {
            index >= APM_TABLE.size -> APM_TABLE.last()
            else -> APM_TABLE[index]
        }
    }

    fun calculateSegmentApm(distanceMeters: Double, gradientPct: Double): Double {
        if (distanceMeters <= 0.0 || gradientPct <= 0.0) return 0.0
        val baseKmCoeff = getKmCoefficient(gradientPct)
        return (distanceMeters / 1000.0) * baseKmCoeff
    }
